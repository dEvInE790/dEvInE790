/**
 * Generates supabase/setup.sql = supabase/schema.sql + the site's starting content.
 * Run with: npm run supabase:sql
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { seedCategories } from "../src/lib/seed-catalogue";
import { seedProjects } from "../src/lib/seed-projects";
import { seedTestimonials } from "../src/lib/seed-testimonials";

const root = process.cwd();
const q = (v: string | null | undefined) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const lines: string[] = [];
lines.push(`
-- ─── Starting content (inserted only the first time) ───────────────────────
do $seed$
begin
  if exists (select 1 from public.site_meta where key = 'seeded') then
    return;
  end if;
`);

lines.push(`  insert into public.categories (slug, name, singular, tagline, intro, cover_src, cover_alt, customisation, sort) values`);
lines.push(
  seedCategories
    .map((c, i) => `    (${q(c.slug)}, ${q(c.name)}, ${q(c.singular)}, ${q(c.tagline)}, ${q(c.intro)}, ${q(c.cover.src)}, ${q(c.cover.alt)}, ${j(c.customisation)}, ${i})`)
    .join(",\n") + "\n  on conflict (slug) do nothing;\n"
);

const productRows = seedCategories.flatMap((c) =>
  c.products.map((p, i) => `    (${q(c.slug)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.summary)}, ${q(p.description)}, ${j(p.features)}, ${j(p.images)}, ${i})`)
);
lines.push(`  insert into public.products (category_id, slug, name, summary, description, features, images, sort)
  select c.id, v.slug, v.name, v.summary, v.description, v.features, v.images, v.sort
  from (values
${productRows.join(",\n")}
  ) as v (category_slug, slug, name, summary, description, features, images, sort)
  join public.categories c on c.slug = v.category_slug
  on conflict (category_id, slug) do nothing;
`);

if (seedProjects.length) {
  lines.push(`  insert into public.projects (seed_key, title, category, description, image_src, image_alt, video_src, size, focus, sort) values`);
  lines.push(
    seedProjects
      .map((p, i) => `    (${q(p.id)}, ${q(p.title)}, ${q(p.category)}, ${q(p.description)}, ${q(p.image.src)}, ${q(p.image.alt)}, ${q(p.video ?? null)}, ${q(p.size)}, ${q(p.focus ?? null)}, ${i})`)
      .join(",\n") + "\n  on conflict (seed_key) do nothing;\n"
  );
}

if (seedTestimonials.length) {
  lines.push(`  insert into public.testimonials (quote, name, detail, sort) values`);
  lines.push(seedTestimonials.map((t, i) => `    (${q(t.quote)}, ${q(t.name)}, ${q(t.detail ?? null)}, ${i})`).join(",\n") + ";\n");
}

lines.push(`  insert into public.site_meta (key, value) values ('seeded', now()::text) on conflict (key) do nothing;
end
$seed$;

-- ─── Your admins ───────────────────────────────────────────────────────────
-- 1. FIRST create each staff member's login: Authentication → Users → Add user
--    → "Create new user", enter their email and a password, tick
--    "Auto Confirm User".
-- 2. THEN, in a new SQL query, run this line with their email (it only works
--    for accounts that already exist):
--
--    insert into public.admin_users (user_id, email)
--    select id, email from auth.users where lower(email) = lower('name@example.com')
--    on conflict (user_id) do nothing;
--
-- To remove someone's admin access:
--    delete from public.admin_users where lower(email) = lower('name@example.com');
`);

const schema = readFileSync(join(root, "supabase/schema.sql"), "utf8");
writeFileSync(
  join(root, "supabase/setup.sql"),
  `${schema.trimEnd()}\n${lines.join("\n")}`.replace(
    "-- Run this whole file once",
    "-- GENERATED by `npm run supabase:sql` from schema.sql + the starting content.\n-- Run this whole file once"
  )
);
console.log("Wrote supabase/setup.sql");
