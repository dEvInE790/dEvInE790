-- ─── Admin allow-list ──────────────────────────────────────────────────────
-- Admin rights are tied to an existing login account (by its user id), so
-- nobody can gain them by later signing up with an admin's email address.
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  email text,
  created_at timestamptz not null default now()
);
alter table public.admin_users enable row level security;
-- No policies on purpose: the list can only be read or changed here, in the SQL editor.

-- True when the signed-in user is on the allow-list and their email is confirmed.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $$
  select exists (
    select 1
    from public.admin_users a
    join auth.users u on u.id = a.user_id
    where a.user_id = auth.uid()
      and u.email_confirmed_at is not null
  );
$$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- ─── Content tables ────────────────────────────────────────────────────────
create table if not exists public.site_meta (key text primary key, value text not null);
alter table public.site_meta enable row level security;

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 80),
  name text not null check (char_length(name) between 1 and 60),
  singular text not null check (char_length(singular) between 1 and 60),
  tagline text not null default '' check (char_length(tagline) <= 120),
  intro text not null default '' check (char_length(intro) <= 600),
  cover_src text not null default '' check (char_length(cover_src) <= 400),
  cover_alt text not null default '' check (char_length(cover_alt) <= 200),
  customisation jsonb not null default '[]'::jsonb check (jsonb_typeof(customisation) = 'array'),
  sort integer not null default 0,
  visible boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories (id) on delete cascade,
  slug text not null check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(slug) <= 80),
  name text not null check (char_length(name) between 1 and 100),
  summary text not null default '' check (char_length(summary) <= 160),
  description text not null default '' check (char_length(description) <= 1500),
  features jsonb not null default '[]'::jsonb check (jsonb_typeof(features) = 'array'),
  images jsonb not null default '[]'::jsonb check (jsonb_typeof(images) = 'array' and jsonb_array_length(images) <= 8),
  sort integer not null default 0,
  visible boolean not null default true,
  updated_at timestamptz not null default now(),
  unique (category_id, slug)
);
create index if not exists products_category_sort on public.products (category_id, sort);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  seed_key text unique,
  title text not null check (char_length(title) between 1 and 120),
  category text not null check (category in ('sofas','bedroom','wardrobes','tv','tables','kitchen','dining','office','windows')),
  description text not null default '' check (char_length(description) <= 600),
  image_src text not null check (char_length(image_src) between 1 and 400),
  image_alt text not null default '' check (char_length(image_alt) <= 200),
  video_src text check (video_src is null or char_length(video_src) <= 400),
  size text not null default 'regular' check (size in ('regular','wide','tall')),
  focus text check (focus is null or focus ~ '^[0-9]{1,3}% [0-9]{1,3}%$'),
  sort integer not null default 0,
  visible boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.testimonials (
  id bigint generated by default as identity primary key,
  quote text not null check (char_length(quote) between 1 and 800),
  name text not null check (char_length(name) between 1 and 80),
  detail text check (detail is null or char_length(detail) <= 120),
  sort integer not null default 0,
  visible boolean not null default true,
  updated_at timestamptz not null default now()
);

-- Keep updated_at current.
create or replace function public.touch_updated_at() returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;
do $$
declare t text;
begin
  foreach t in array array['categories','products','projects','testimonials'] loop
    execute format('drop trigger if exists touch_%1$s on public.%1$I', t);
    execute format('create trigger touch_%1$s before update on public.%1$I for each row execute function public.touch_updated_at()', t);
  end loop;
end $$;

-- ─── Row-level security ────────────────────────────────────────────────────
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.projects enable row level security;
alter table public.testimonials enable row level security;

grant select on public.categories, public.products, public.projects, public.testimonials to anon, authenticated;
grant insert, update, delete on public.categories, public.products, public.projects, public.testimonials to authenticated;

drop policy if exists "read visible categories" on public.categories;
create policy "read visible categories" on public.categories for select to anon, authenticated
  using (visible or public.is_admin());

drop policy if exists "read visible products" on public.products;
create policy "read visible products" on public.products for select to anon, authenticated
  using (
    (visible and exists (select 1 from public.categories c where c.id = category_id and c.visible))
    or public.is_admin()
  );

drop policy if exists "read visible projects" on public.projects;
create policy "read visible projects" on public.projects for select to anon, authenticated
  using (visible or public.is_admin());

drop policy if exists "read visible testimonials" on public.testimonials;
create policy "read visible testimonials" on public.testimonials for select to anon, authenticated
  using (visible or public.is_admin());

do $$
declare t text;
begin
  foreach t in array array['categories','products','projects','testimonials'] loop
    execute format('drop policy if exists "admins insert" on public.%I', t);
    execute format('drop policy if exists "admins update" on public.%I', t);
    execute format('drop policy if exists "admins delete" on public.%I', t);
    execute format('create policy "admins insert" on public.%I for insert to authenticated with check (public.is_admin())', t);
    execute format('create policy "admins update" on public.%I for update to authenticated using (public.is_admin()) with check (public.is_admin())', t);
    execute format('create policy "admins delete" on public.%I for delete to authenticated using (public.is_admin())', t);
  end loop;
end $$;

-- Reorder a list in one step: p_ids in the new order (admins only).
create or replace function public.admin_reorder(p_table text, p_ids bigint[])
returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  if not public.is_admin() then
    raise exception 'Only admins can reorder content' using errcode = '42501';
  end if;
  if p_table not in ('categories','products','projects','testimonials') then
    raise exception 'Unknown list %', p_table;
  end if;
  execute format(
    'update public.%I t set sort = x.ord - 1 from unnest($1) with ordinality as x(id, ord) where t.id = x.id',
    p_table
  ) using p_ids;
end $$;
revoke all on function public.admin_reorder(text, bigint[]) from public;
grant execute on function public.admin_reorder(text, bigint[]) to authenticated;

-- ─── Media storage (photos & videos) ───────────────────────────────────────
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('media', 'media', true, 52428800, array['image/jpeg','image/png','image/webp','video/mp4','video/quicktime'])
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- Anyone can VIEW files (the bucket is public); only admins can add, change or delete them.
drop policy if exists "media admins read" on storage.objects;
create policy "media admins read" on storage.objects for select to authenticated
  using (bucket_id = 'media' and public.is_admin());
drop policy if exists "media admins insert" on storage.objects;
create policy "media admins insert" on storage.objects for insert to authenticated
  with check (bucket_id = 'media' and public.is_admin());
drop policy if exists "media admins update" on storage.objects;
create policy "media admins update" on storage.objects for update to authenticated
  using (bucket_id = 'media' and public.is_admin());
drop policy if exists "media admins delete" on storage.objects;
create policy "media admins delete" on storage.objects for delete to authenticated
  using (bucket_id = 'media' and public.is_admin());
